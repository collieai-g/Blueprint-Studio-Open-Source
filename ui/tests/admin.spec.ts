import { expect, test, type APIRequestContext } from '@playwright/test';

const allowed = process.env.BLUEPRINT_E2E_ALLOW_WRITES === '1';
const email = process.env.BLUEPRINT_E2E_EMAIL;
const password = process.env.BLUEPRINT_E2E_PASSWORD;
const unique = `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`;
const memberName = `ui-member-${unique}`;
const memberEmail = `ui-${unique}@example.invalid`;
const groupName = `ui-group-${unique}`;
const tokenName = `ui-token-${unique}`;
const activationPassword = `Browser-activation-${unique}!`;
let api: APIRequestContext;
let originalSettings: any;

test.describe('real administrator lifecycle', () => {
  test.setTimeout(90_000);
  test.skip(!allowed || !email || !password, 'Requires a disposable real workspace and explicit E2E write opt-in.');
  test.beforeAll(async ({ playwright, baseURL }) => {
    api = await playwright.request.newContext({ baseURL, extraHTTPHeaders: { 'X-Blueprint-Request': '1' } });
    expect((await api.post('/api/v1/login', { data: { email, password } })).ok()).toBeTruthy();
    originalSettings = await (await api.get('/api/v1/settings')).json();
  });
  test.afterAll(async () => {
    if (!api) return;
    if (originalSettings) await api.patch('/api/v1/settings', { data: { company: originalSettings.company, modules: originalSettings.modules } });
    const users = await (await api.get('/api/v1/users')).json();
    for (const user of users) if (user.email === memberEmail) await api.patch(`/api/v1/users/${user.id}`, { data: { active: false, groups: [] } });
    const groups = await (await api.get('/api/v1/resources/group')).json();
    for (const group of groups) if (group.name === groupName) await api.delete(`/api/v1/resource/${group.id}?expected_version=${group.version}`);
    const tokens = await (await api.get('/api/v1/tokens')).json();
    for (const token of tokens) if (token.name === tokenName && !token.revoked_at) await api.delete(`/api/v1/tokens/${token.id}`);
    await api.dispose();
  });

  test('browser sign in, persistent settings, group invitation activation and scoped token revocation', async ({ browser, baseURL }) => {
    const owner = await browser.newContext({ baseURL });
    const page = await owner.newPage();
    const browserErrors: string[] = [];
    page.on('pageerror', error => browserErrors.push(error.message));
    await page.goto('/');
    await page.getByLabel('電郵地址', { exact: true }).fill(email!);
    await page.getByLabel('密碼', { exact: true }).fill(password!);
    await page.getByRole('button', { name: '登入工作空間', exact: true }).click();
    await expect(page.getByRole('heading', { name: '工作總覽', exact: true })).toBeVisible();
    await page.goto('/#settings');
    await page.getByLabel('公司簡介 選填').fill(`Browser acceptance ${unique}`);
    await page.getByRole('button', { name: '儲存變更', exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: '工作空間設定已儲存' })).toBeVisible();
    await page.reload();
    await expect(page.getByLabel('公司簡介 選填')).toHaveValue(`Browser acceptance ${unique}`);
    await page.getByRole('button', { name: '功能模組', exact: true }).click();
    const forms = page.getByRole('switch', { name: /表單/ });
    await forms.uncheck();
    const collections = page.getByRole('switch', { name: /^個人收藏/ });
    await collections.uncheck();
    await page.getByRole('button', { name: '儲存模組設定', exact: true }).click();
    await expect(page.getByRole('link', { name: '表單', exact: true })).toHaveCount(0);
    await page.goto('/#files');
    await expect(page.getByRole('heading', { name: '文件', exact: true })).toBeVisible();
    await expect(page.locator('.content-page .error-notice')).toHaveCount(0);
    await expect(page.getByRole('button', { name: '上傳', exact: true })).toBeEnabled();
    await page.goto('/#settings');
    await page.getByRole('button', { name: '功能模組', exact: true }).click();
    await forms.check();
    await collections.check();
    await page.getByRole('button', { name: '儲存模組設定', exact: true }).click();
    await expect(page.getByRole('link', { name: '表單', exact: true })).toBeVisible();

    await page.goto('/#users');
    await page.getByRole('button', { name: /^群組/ }).click();
    await page.getByRole('button', { name: '建立群組', exact: true }).click();
    let dialog = page.getByRole('dialog', { name: '建立群組' });
    await dialog.getByLabel('群組名稱').fill(groupName);
    await dialog.getByRole('button', { name: '儲存成員資料' }).click();
    await expect(page.locator('.group-card').filter({ hasText: groupName })).toBeVisible();
    await page.getByRole('button', { name: /^成員 \d/ }).click();
    await page.getByRole('button', { name: '新增成員', exact: true }).click();
    dialog = page.getByRole('dialog', { name: '新增公司成員' });
    await dialog.getByLabel('名稱', { exact: true }).fill(memberName);
    await dialog.getByLabel('電郵地址', { exact: true }).fill(memberEmail);
    await dialog.getByRole('combobox', { name: '角色', exact: true }).selectOption('viewer');
    await dialog.getByRole('checkbox', { name: groupName }).check();
    await dialog.getByRole('button', { name: '儲存成員資料' }).click();
    const activation = dialog.getByLabel('啟用連結', { exact: true });
    await expect(activation).toHaveValue(/\/activate\?token=/);
    const activateUrl = await activation.inputValue();
    await dialog.getByRole('button', { name: '完成', exact: true }).click();
    const member = page.getByRole('row').filter({ hasText: memberEmail });
    await expect(member).toContainText('檢視者');
    await expect(member).toContainText(groupName);
    const invitee = await browser.newContext({ baseURL });
    const inviteePage = await invitee.newPage();
    await inviteePage.goto(activateUrl);
    await inviteePage.getByLabel('登入密碼', { exact: true }).fill(activationPassword);
    await inviteePage.getByLabel('確認密碼', { exact: true }).fill(activationPassword);
    await inviteePage.getByRole('button', { name: '啟用帳戶', exact: true }).click();
    await expect(inviteePage.getByRole('heading', { name: '工作總覽', exact: true })).toBeVisible();
    await inviteePage.goto('/#files');
    await expect(inviteePage.getByRole('heading', { name: '文件', exact: true })).toBeVisible();
    await expect(inviteePage.getByRole('button', { name: '上傳', exact: true })).toBeDisabled();
    await invitee.close();
    await page.getByRole('button', { name: '重新整理成員及群組' }).click();
    await member.getByRole('button', { name: '停用', exact: true }).click();
    await expect(member).toContainText('已停用');

    await page.goto('/#tokens');
    await page.getByRole('button', { name: '建立 API 金鑰', exact: true }).click();
    dialog = page.getByRole('dialog', { name: '建立 API 金鑰' });
    await dialog.getByLabel('用途名稱').fill(tokenName);
    await dialog.getByRole('button', { name: '建立金鑰', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'API 金鑰已建立' });
    await expect(dialog.getByLabel('新建立的 API 金鑰')).not.toHaveValue('');
    await dialog.getByRole('button', { name: '完成並關閉', exact: true }).click();
    let row = page.getByRole('row').filter({ hasText: tokenName });
    await expect(row).toContainText('content:read');
    await row.getByRole('button', { name: '撤銷', exact: true }).click();
    await expect(row.getByRole('button', { name: '撤銷', exact: true })).toHaveCount(0);
    await page.reload();
    await expect(page.getByLabel('新建立的 API 金鑰')).toHaveCount(0);
    row = page.getByRole('row').filter({ hasText: tokenName });
    if (await row.count()) await expect(row).toContainText('已撤銷');
    expect(browserErrors).toEqual([]);
    await owner.close();
  });
});
